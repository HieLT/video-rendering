const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const manifest=JSON.parse(fs.readFileSync('extensions/dola30/manifest.json','utf8'));
const source=fs.readFileSync('extensions/dola30/'+manifest.background.service_worker,'utf8');
const ctx=vm.createContext({});
vm.runInContext(source.slice(source.indexOf('function patchSeedance25Model('),source.indexOf('function patchActionBarDuration(')),ctx);
const patch=x=>JSON.parse(ctx.patchSeedance25Model(JSON.stringify(x)));
const base={key:'video-model',default_selection_id:4,default_selection_index:0,option_list:[{id:4,option_key:'seedance_v2.0'},{id:1,option_key:'ic_mini'}]};
const result=patch(base);
assert.equal(result.option_list[2].option_key,'seedance_v2.5');
assert.equal(result.option_list[2].extra.subs_only_tag,'enhanced');
assert.equal(result.default_selection_id,4);
assert.deepEqual(result.option_list.slice(0,2),base.option_list);
assert.deepEqual(patch(result),result);
assert.equal(JSON.parse(JSON.parse(patch({template:JSON.stringify({template:JSON.stringify(base)})}).template).template).option_list[2].option_key,'seedance_v2.5');
for(const x of [{...base,key:'image-model'},{...base,option_list:[{id:7,option_key:'other'},...base.option_list]},{key:'video-model',option_list:[]}])assert.deepEqual(patch(x),x);
const server={...base,option_list:[...base.option_list,{id:7,option_key:'seedance_v2.5',extra:{server:'preserve'}}]};
assert.deepEqual(patch(server),server);
assert.equal(ctx.patchSeedance25Model('bad json'),'bad json');
console.log('PASS model insertion, nested JSON, defaults, entitlement, existing options, ID conflicts, idempotence');
